import { readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import sharp from 'sharp'

const root = process.cwd()
const publicDirectory = path.join(root, 'public')
const imageDirectory = path.join(publicDirectory, 'assets')
const destination = path.join(root, 'src', 'content', 'generatedImageDimensions.js')
const supported = new Set(['.avif', '.gif', '.jpeg', '.jpg', '.png', '.svg', '.webp'])

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true })
  const files = []
  for (const entry of entries) {
    const fullPath = path.join(directory, entry.name)
    if (entry.isDirectory()) files.push(...await walk(fullPath))
    else if (supported.has(path.extname(entry.name).toLowerCase())) files.push(fullPath)
  }
  return files
}

const dimensions = {}
for (const file of await walk(imageDirectory)) {
  const metadata = await sharp(file).metadata()
  if (!metadata.width || !metadata.height) continue
  const key = path.relative(publicDirectory, file).split(path.sep).join('/')
  dimensions[key] = [metadata.width, metadata.height]
}

const source = `// Generated by npm run images:dimensions. Do not edit by hand.\nexport const GENERATED_IMAGE_DIMENSIONS = ${JSON.stringify(dimensions, null, 2)}\n`
await writeFile(destination, source)
console.log(`Recorded intrinsic dimensions for ${Object.keys(dimensions).length} images.`)
